import { strict as assert } from 'node:assert';
import { roomStatuses, statusAt } from './kiosk-time.js';
const data = {entries:[{starts:100, ends:200}]};
assert.deepEqual(roomStatuses({ 1: data, 2: { entries: [] }, 3: { entries: [], unavailable: true }, 4: { entries: [], valid_until: 101 } }, 2000, 2000, 100), { 1: 'Đang họp', 2: 'Trống', 3: 'Không xác định', 4: 'Không xác định' });
assert.deepEqual(roomStatuses(null, 0, 0, 100), {});
assert.equal(statusAt(null, 0, 0, 100), 'Không xác định');
assert.equal(statusAt({entries:[{starts:103,ends:200}]}, 0, 0, 100, 5000), 'Không xác định');
assert.equal(statusAt({entries:[],valid_until:103}, 0, 0, 100, 5000), 'Không xác định');
assert.equal(statusAt({entries:[{starts:101,ends:200}]}, 0, 0, 100), 'Không xác định');
assert.equal(statusAt({entries:[{starts:110,ends:200}]}, 0, 0, 100, 0, 30000), 'Không xác định');
assert.equal(statusAt({entries:[{starts:110,ends:200}]}, 0, 0, 100, 0, 0), 'Trống');
assert.equal(statusAt({entries:[],valid_until:130}, 0, 0, 100, 0, 30000), 'Không xác định');
assert.equal(statusAt({entries:[]}, 0, 0, NaN), 'Không xác định');
assert.equal(statusAt({entries:[]}, NaN, 0, 100), 'Không xác định');
assert.equal(statusAt({entries:[{starts:null, ends:200}]}, 0, 0, 100), 'Không xác định');
assert.equal(statusAt({entries:[], valid_until:'invalid'}, 0, 0, 100), 'Không xác định');
assert.equal(statusAt({entries:[]}, 0, 0, 100, -1), 'Không xác định');
assert.equal(statusAt({entries:[]}, 0, 0, 100, 0, -1), 'Không xác định');
assert.equal(statusAt({entries:[null]}, 0, 0, 100), 'Không xác định');
assert.equal(statusAt({entries:[{starts:200, ends:100}]}, 0, 0, 100), 'Không xác định');
assert.equal(statusAt({entries:[{starts:1e300, ends:1e301}]}, 0, 0, 100), 'Không xác định');
assert.equal(statusAt({entries:[{starts:-1, ends:200}]}, 0, 0, 100), 'Không xác định');
assert.equal(statusAt({entries:[{starts:100.5, ends:200}]}, 0, 0, 100), 'Không xác định');
assert.equal(statusAt({entries:[]}, 0, 0, 1e300), 'Không xác định');
assert.equal(statusAt(data, 0, 0, 100), 'Không xác định');
assert.equal(statusAt(data, 2000, 2000, 100), 'Đang họp');
assert.equal(statusAt(data, 100000, 100000, 100, 5000), 'Không xác định');
assert.equal(statusAt(data, 102000, 102000, 100), 'Trống');
assert.equal(statusAt(data, 899999, 899999, 100), 'Trống');
assert.equal(statusAt(data, 870000, 870000, 100, 0, 30000), 'Không xác định');
assert.equal(statusAt(data, 900000, 0, 100), 'Không xác định');
assert.equal(statusAt(data, 0, 900000, 100), 'Không xác định');
assert.equal(statusAt(data, 0, -1, 100), 'Không xác định');
// A wall-clock jump or sleeping monotonic clock must not advance the schedule.
assert.equal(statusAt(data, 2000, 102000, 100), 'Không xác định');
assert.equal(statusAt(data, 102000, 2000, 100), 'Không xác định');
assert.equal(statusAt(data, 102000, 102000, 100), 'Trống');
assert.equal(statusAt(data, 2000, 3000, 100), 'Đang họp');
assert.equal(statusAt({entries:[{starts:100, ends:102}]}, 2000, 3000, 100), 'Không xác định');
assert.equal(statusAt(data, 2000, 3001, 100), 'Không xác định');
assert.equal(statusAt({...data, valid_until: 150}, 50000, 50000, 100), 'Không xác định');
